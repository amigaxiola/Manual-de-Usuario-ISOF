      <h1>Interfaz de ventas</h1>
      <p>
        El módulo de ventas está diseñado para agilizar el proceso de atención al cliente mediante
        una selección visual y dinámica de productos y sabores. Esta interfaz se comunica directamente
        con la configuración previa de <strong>Sabores del Día</strong> para mostrar únicamente lo que está disponible en el momento.
      </p>
    </div>
  </section>

  <section class="content">
    <div class="container-fluid">
      <h2>Elementos principales</h2>
      <ul>
        <li>Botones para seleccionar el producto a vender (bola, malteada, sundae, vaso grande, extra).</li>
        <li>Panel con el botón <strong>Volver</strong> para regresar al menú principal.</li>
        <li>Lista de productos seleccionados hasta el momento.</li>
        <li>Botón <strong>Confirmar venta</strong> para finalizar la operación.</li>
      </ul>

      <h2>Flujo de venta</h2>
      <ol>
        <li>Seleccionar el producto deseado.</li>
        <li>Elegir presentación (cono o vaso, en caso de bolas).</li>
        <li>Seleccionar los sabores según la cantidad de bolas.</li>
        <li>Presionar <strong>Aceptar</strong> para regresar a la interfaz principal de ventas.</li>
        <li>Agregar más productos si es necesario o confirmar la venta.</li>
      </ol>

      <h2>Finalización</h2>
      <p>
        Al confirmar la venta, se muestra una pantalla con los datos de la operación, donde se selecciona
        el método de pago y el monto a cobrar.
      </p>
    </div>
  </section>
