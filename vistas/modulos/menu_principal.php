<h1>Menú principal</h1>

<p>
Esta interfaz actúa como el panel central de control del sistema, proporcionando acceso
directo a todos los módulos operativos y administrativos del punto de venta.
</p>

<p>
Se manejan dos menús diferentes: uno para la gerencia y otro para los empleados.
</p>

<h2>Panel lateral de usuario</h2>
<p>
Aquí se muestran los datos básicos del usuario que ha iniciado sesión (nombre e ID único).
También se cuenta con un botón de <strong>ayuda</strong>, que dirige a información de contacto en caso de dudas,
y un botón de <strong>cerrar sesión</strong> en la parte inferior.
</p>

<h2>Botones de gerencia</h2>
<ul>
  <li><strong>Empleados:</strong> registro y administración de roles de usuario.</li>
  <li><strong>Activar sabores del día:</strong> seleccionar qué sabores estarán disponibles para la venta inmediata.</li>
</ul>

<h2>Botones de empleados</h2>
<p>
Los empleados cuentan con las funciones cotidianas del negocio:
</p>
<ul>
  <li><strong>Venta:</strong> interfaz de cobro y selección de productos.</li>
  <li><strong>Sabores:</strong> gestión del catálogo general de sabores.</li>
  <li><strong>Inventario:</strong> consulta de existencias.</li>
  <li><strong>Reportes:</strong> generación de informes de ventas y movimientos.</li>
  <li><strong>Compras:</strong> registro de adquisición de insumos.</li>
  <li><strong>Producción:</strong> control y registro de fabricación de helados.</li>
</ul>
