        <li>Filtros disponibles:
          <ul>
            <li>Rango de tiempo (día, semana o mes).</li>
            <li>Empleado específico.</li>
            <li>Clasificación de registros (ventas al público o compras a proveedores).</li>
            <li>Movimiento de un sabor o insumo específico.</li>
          </ul>
        </li>
