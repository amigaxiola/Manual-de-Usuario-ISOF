      </p>
      <ul>
        <li>Nombre del insumo adquirido.</li>
        <li>Cantidad comprada.</li>
        <li>Proveedor asociado.</li>
        <li>Fecha de la compra.</li>
      </ul>

      <h2>Formulario de registro de proveedores</h2>
      <p>
